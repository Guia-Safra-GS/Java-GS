-- Cursor explicito 1: slots ativos com classificacao de risco hidrico
DECLARE
    CURSOR c_slots_status IS
        SELECT sl.POSITION, sp.COMMON_NAME, sp.MIN_HUMIDITY,
               (SELECT AVG(r.HUMIDITY) FROM TB_MON_READING r WHERE r.SLOT_ID = sl.ID) AS avg_hum
          FROM TB_CAD_SLOT sl
          JOIN TB_CAD_SPECIES sp ON sp.ID = sl.SPECIES_ID
         WHERE sl.STATUS = 'ACTIVE'
         ORDER BY avg_hum;

    v_classification VARCHAR2(20);
    v_count_risk     NUMBER := 0;
    v_count_ok       NUMBER := 0;
    v_total          NUMBER := 0;
BEGIN
    DBMS_OUTPUT.PUT_LINE('=====================================================');
    DBMS_OUTPUT.PUT_LINE('   CURSOR 1 - RISCO HIDRICO POR SLOT                 ');
    DBMS_OUTPUT.PUT_LINE('=====================================================');
    DBMS_OUTPUT.PUT_LINE(RPAD('Slot',8)||RPAD('Cultura',12)||RPAD('Umid.Media',12)||
        RPAD('Minimo',10)||'Situacao');
    DBMS_OUTPUT.PUT_LINE(RPAD('-',60,'-'));

    FOR reg IN c_slots_status LOOP
        -- Tomada de decisao: comparar media com o minimo da cultura
        IF reg.avg_hum IS NULL THEN
            v_classification := 'Sem leituras';
        ELSIF reg.avg_hum < reg.MIN_HUMIDITY THEN
            v_classification := 'EM RISCO';
            v_count_risk := v_count_risk + 1;
        ELSE
            v_classification := 'Adequado';
            v_count_ok := v_count_ok + 1;
        END IF;

        DBMS_OUTPUT.PUT_LINE(RPAD(reg.POSITION,8)||RPAD(reg.COMMON_NAME,12)||
            RPAD(NVL(TO_CHAR(ROUND(reg.avg_hum,1)),'-'),12)||
            RPAD(reg.MIN_HUMIDITY,10)||v_classification);
        v_total := v_total + 1;
    END LOOP;

    DBMS_OUTPUT.PUT_LINE(RPAD('-',60,'-'));
    DBMS_OUTPUT.PUT_LINE('Total de slots ativos: '||v_total);
    DBMS_OUTPUT.PUT_LINE('  Em risco: '||v_count_risk||'   Adequados: '||v_count_ok);
END;
