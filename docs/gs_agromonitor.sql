-- =====================================================================
-- GLOBAL SOLUTION 2026/1 - FIAP - 2TDS
-- Projeto: Monitoramento agricola inteligente para pequenos e medios
--          produtores. Combina sensores de campo (ESP32/IoT) com previsao
--          climatica derivada de satelite, automatizando alertas e rega
--          por meio de inteligencia no banco (PL/SQL).
--
-- Arquivo: gs_agromonitor_completo.sql  (script unico: roda do inicio ao fim)
-- Conteudo: DDL + Procedures + Carga + Automacao (trigger/procedures) +
--           Function + Relatorios (cursores e JOIN).
-- Banco:   Oracle (compativel com o ambiente da FIAP)
--
-- ORDEM DE EXECUCAO:
--   1) Limpeza e DDL
--   2) Procedures de insercao (SP_INSERT_*)
--   3) Blocos anonimos de carga (80+ registros)
--   4) Automacao: package + trigger (rega de emergencia / alerta de geada)
--   5) Function de apoio
--   6) Relatorios com cursores explicitos e JOIN
--
-- CONVENCOES (alinhadas ao script da sprint anterior - ClyvoCare):
--   - Prefixos: TB_CAD_ (cadastro)  |  TB_MON_ (monitoramento/operacao)
--   - PK: NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY
--   - Atributos em INGLES (evita @Column no JPA do Java)
--   - CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP
--   - Constraints nomeadas: FK_, UK_, CK_
--   - Texto de PL/SQL e mensagens em PORTUGUES humanizado
--
-- DOMINIOS DE APLICACAO (separacao na camada de aplicacao, nao no banco):
--   C#  (Cadastro) -> escreve TB_CAD_SPECIES, TB_CAD_SLOT
--   Java (Operacao)-> escreve TB_CAD_USER, TB_MON_CLIMATE_FORECAST,
--                     TB_MON_READING, TB_MON_WATERING_EVENT, TB_MON_ALERT;
--                     le TB_CAD_SLOT (somente leitura, para validar FK)
--   O banco e um schema unico; a FK entre dominios e garantida pelo Oracle.
-- =====================================================================

SET SERVEROUTPUT ON SIZE UNLIMITED;
SET LINESIZE 200;

-- ---------------------------------------------------------------------
-- LIMPEZA (ignore erros na primeira execucao)
-- ---------------------------------------------------------------------
BEGIN
    FOR t IN (
        SELECT table_name FROM user_tables
        WHERE table_name IN (
            'TB_MON_ALERT','TB_MON_WATERING_EVENT','TB_MON_READING',
            'TB_MON_CLIMATE_FORECAST','TB_MON_ERROR_LOG','TB_MON_RAW_TELEMETRY',
            'TB_CAD_SLOT','TB_CAD_SPECIES','TB_CAD_USER'
        )
    ) LOOP
        EXECUTE IMMEDIATE 'DROP TABLE '||t.table_name||' CASCADE CONSTRAINTS PURGE';
    END LOOP;
END;
