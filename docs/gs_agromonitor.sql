-- Estas novas leituras criticas, inseridas APOS a trigger existir,
-- acionam a rega automatica e os alertas ao vivo.
-- ---------------------------------------------------------------------
DECLARE
    v_s_a1 NUMBER; v_s_b2 NUMBER; v_s_c2 NUMBER;
BEGIN
