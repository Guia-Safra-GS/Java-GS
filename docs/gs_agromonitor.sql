-- SPECIES: catalogo de culturas. Guarda a REGRA de negocio (faixas ideais).
CREATE TABLE TB_CAD_SPECIES (
    ID             NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    COMMON_NAME    VARCHAR2(80)  NOT NULL UNIQUE,
    SCIENTIFIC_NAME VARCHAR2(120),
    MIN_HUMIDITY   NUMBER(5,2)   NOT NULL,   -- % minima de umidade tolerada
    MAX_HUMIDITY   NUMBER(5,2)   NOT NULL,   -- % maxima de umidade tolerada
    FROST_MIN_TEMP NUMBER(4,1),              -- temp (C) abaixo da qual ha risco de geada
    WATERING_ML    NUMBER(6)     NOT NULL,   -- volume de agua por rega (ml)
    CREATED_AT     TIMESTAMP DEFAULT SYSTIMESTAMP,
    CONSTRAINT CK_SPECIES_MIN_HUM CHECK (MIN_HUMIDITY BETWEEN 0 AND 100),
    CONSTRAINT CK_SPECIES_MAX_HUM CHECK (MAX_HUMIDITY BETWEEN 0 AND 100),
    CONSTRAINT CK_SPECIES_RANGE   CHECK (MIN_HUMIDITY < MAX_HUMIDITY),
    CONSTRAINT CK_SPECIES_ML      CHECK (WATERING_ML > 0)
);

-- SLOT: cada vaga de plantio monitorada. FILHO de SPECIES (relacao 1:N).
-- Atende o requisito do .NET "pelo menos um relacionamento 1:N".
-- Remocao e LOGICA (campo STATUS), preservando o historico de leituras.
CREATE TABLE TB_CAD_SLOT (
    ID          NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    SPECIES_ID  NUMBER(19)   NOT NULL,
    POSITION    VARCHAR2(20) NOT NULL,        -- ex.: "A1", "B3"
    PLANTED_AT  DATE         DEFAULT SYSDATE NOT NULL,
    STATUS      VARCHAR2(15) DEFAULT 'ACTIVE' NOT NULL,
    CREATED_AT  TIMESTAMP DEFAULT SYSTIMESTAMP,
    CONSTRAINT FK_SLOT_SPECIES FOREIGN KEY (SPECIES_ID) REFERENCES TB_CAD_SPECIES(ID),
    CONSTRAINT CK_SLOT_STATUS  CHECK (STATUS IN ('ACTIVE','INACTIVE','HARVESTED'))
);


-- USER: produtores/operadores que acessam pelo app (autenticacao JWT no Java).
CREATE TABLE TB_CAD_USER (
    ID            NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    NAME          VARCHAR2(100) NOT NULL,
    EMAIL         VARCHAR2(120) NOT NULL UNIQUE,
    PASSWORD_HASH VARCHAR2(255) NOT NULL,     -- hash BCrypt; nunca senha pura
    ROLE          VARCHAR2(15)  DEFAULT 'PRODUCER' NOT NULL,
    CREATED_AT    TIMESTAMP DEFAULT SYSTIMESTAMP,
    CONSTRAINT CK_USER_ROLE CHECK (ROLE IN ('PRODUCER','ADMIN'))
);

-- CLIMATE_FORECAST: dado vindo da API externa de clima (derivada de satelite).
-- Guarda SO os campos que a regra de negocio usa. O JSON cru vai para a
-- colecao NoSQL (exemplo NoSQL exigido na pag. 44).
CREATE TABLE TB_MON_CLIMATE_FORECAST (
    ID             NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    FORECAST_DATE  DATE          NOT NULL,    -- dia a que a previsao se refere
    MIN_TEMP       NUMBER(4,1),
    MAX_TEMP       NUMBER(4,1),
    RAINFALL_MM    NUMBER(6,2),               -- precipitacao prevista (mm)
    FROST_PROB     NUMBER(5,2),               -- probabilidade de geada (0 a 100)
    SOURCE         VARCHAR2(40) DEFAULT 'CLIMATE_API' NOT NULL,
    CREATED_AT     TIMESTAMP DEFAULT SYSTIMESTAMP,
    CONSTRAINT CK_FORECAST_FROST CHECK (FROST_PROB BETWEEN 0 AND 100),
    CONSTRAINT CK_FORECAST_TEMP  CHECK (MIN_TEMP <= MAX_TEMP)
);

-- READING: historico de medicoes do sensor.
-- *** CHAVE COMPOSTA *** (SLOT_ID, READ_TIMESTAMP) -> requisito do Java (pag. 32).
-- E a unica tabela que foge do padrao IDENTITY de propósito: sua identidade
-- e naturalmente o par "qual slot + em que momento". No Java vira um
-- @Embeddable ReadingId usado como @EmbeddedId (cobre chave composta E Embedded).
CREATE TABLE TB_MON_READING (
    SLOT_ID        NUMBER(19)   NOT NULL,
    READ_TIMESTAMP TIMESTAMP    NOT NULL,
    HUMIDITY       NUMBER(5,2)  NOT NULL,
    TEMPERATURE    NUMBER(4,1),
    CONSTRAINT PK_READING       PRIMARY KEY (SLOT_ID, READ_TIMESTAMP),
    CONSTRAINT CK_READING_HUM   CHECK (HUMIDITY BETWEEN 0 AND 100),
    CONSTRAINT FK_READING_SLOT  FOREIGN KEY (SLOT_ID) REFERENCES TB_CAD_SLOT(ID)
);

-- WATERING_EVENT: registro de cada acionamento da bomba.
-- ORIGIN distingue rega MANUAL (produtor pelo app) de AUTOMATIC (regra do banco).
-- USER_ID e NULO quando a rega foi automatica (ninguem acionou).
CREATE TABLE TB_MON_WATERING_EVENT (
    ID          NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    SLOT_ID     NUMBER(19)   NOT NULL,
    USER_ID     NUMBER(19),                   -- NULL = rega automatica
    ORIGIN      VARCHAR2(12) NOT NULL,
    VOLUME_ML   NUMBER(6)    NOT NULL,
    EVENT_TIME  TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT CK_WATERING_ORIGIN CHECK (ORIGIN IN ('MANUAL','AUTOMATIC')),
    CONSTRAINT CK_WATERING_ML     CHECK (VOLUME_ML > 0),
    CONSTRAINT FK_WATERING_SLOT   FOREIGN KEY (SLOT_ID) REFERENCES TB_CAD_SLOT(ID),
    CONSTRAINT FK_WATERING_USER   FOREIGN KEY (USER_ID) REFERENCES TB_CAD_USER(ID)
);

-- ALERT: avisos GERADOS pela logica PL/SQL (nao importados da API).
-- Nascem de umidade critica (sensor) ou risco de geada (previsao climatica).
CREATE TABLE TB_MON_ALERT (
    ID          NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    SLOT_ID     NUMBER(19)    NOT NULL,
    ALERT_TYPE  VARCHAR2(20)  NOT NULL,        -- ex.: LOW_HUMIDITY, FROST_RISK
    SEVERITY    VARCHAR2(10)  NOT NULL,
    MESSAGE     VARCHAR2(200),
    ALERT_TIME  TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    RESOLVED    CHAR(1)       DEFAULT 'N' NOT NULL,
    CONSTRAINT CK_ALERT_SEVERITY CHECK (SEVERITY IN ('LOW','MEDIUM','CRITICAL')),
    CONSTRAINT CK_ALERT_RESOLVED CHECK (RESOLVED IN ('S','N')),
    CONSTRAINT FK_ALERT_SLOT     FOREIGN KEY (SLOT_ID) REFERENCES TB_CAD_SLOT(ID)
);

-- ERROR_LOG: registro das excecoes tratadas nas procedures de carga (PL/SQL).
CREATE TABLE TB_MON_ERROR_LOG (
    ID              NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    PROCEDURE_NAME  VARCHAR2(100),
    USER_NAME       VARCHAR2(100),
    OCCURRENCE_DATE TIMESTAMP DEFAULT SYSTIMESTAMP,
    ERROR_CODE      VARCHAR2(20),
    ERROR_MESSAGE   VARCHAR2(2000)
);

-- ---------------------------------------------------------------------
-- INDICES de apoio (consultas mais comuns dos relatorios e da logica)
-- ---------------------------------------------------------------------
CREATE INDEX IX_READING_TIME    ON TB_MON_READING (READ_TIMESTAMP);
CREATE INDEX IX_WATERING_SLOT   ON TB_MON_WATERING_EVENT (SLOT_ID);
CREATE INDEX IX_ALERT_SLOT_RES  ON TB_MON_ALERT (SLOT_ID, RESOLVED);
CREATE INDEX IX_FORECAST_DATE   ON TB_MON_CLIMATE_FORECAST (FORECAST_DATE);

COMMIT;

