-- Cursor explicito 2: consumo de agua por cultura (rega manual + automatica)
DECLARE
    CURSOR c_water_consumption IS
        SELECT sp.COMMON_NAME,
               COUNT(we.ID) AS total_events,
               NVL(SUM(we.VOLUME_ML),0) AS total_ml,
               SUM(CASE WHEN we.ORIGIN = 'AUTOMATIC' THEN 1 ELSE 0 END) AS auto_events
          FROM TB_CAD_SPECIES sp
          JOIN TB_CAD_SLOT sl ON sl.SPECIES_ID = sp.ID
          LEFT JOIN TB_MON_WATERING_EVENT we ON we.SLOT_ID = sl.ID
         GROUP BY sp.COMMON_NAME
         ORDER BY total_ml DESC;

    v_efficiency VARCHAR2(20);
    v_grand_ml   NUMBER := 0;
BEGIN
    DBMS_OUTPUT.PUT_LINE('=====================================================');
    DBMS_OUTPUT.PUT_LINE('   CURSOR 2 - CONSUMO DE AGUA POR CULTURA            ');
    DBMS_OUTPUT.PUT_LINE('=====================================================');
    DBMS_OUTPUT.PUT_LINE(RPAD('Cultura',12)||RPAD('Regas',8)||RPAD('Total(ml)',12)||
        RPAD('Automaticas',13)||'Perfil');
    DBMS_OUTPUT.PUT_LINE(RPAD('-',60,'-'));

    FOR reg IN c_water_consumption LOOP
        -- Tomada de decisao: perfil de consumo
        IF reg.total_ml >= 1000 THEN
            v_efficiency := 'Alto consumo';
        ELSIF reg.total_ml >= 400 THEN
            v_efficiency := 'Moderado';
        ELSE
            v_efficiency := 'Baixo';
        END IF;

        DBMS_OUTPUT.PUT_LINE(RPAD(reg.COMMON_NAME,12)||RPAD(reg.total_events,8)||
            RPAD(reg.total_ml,12)||RPAD(reg.auto_events,13)||v_efficiency);
        v_grand_ml := v_grand_ml + reg.total_ml;
    END LOOP;

    DBMS_OUTPUT.PUT_LINE(RPAD('-',60,'-'));
    DBMS_OUTPUT.PUT_LINE('Consumo total de agua: '||v_grand_ml||' ml');
END;
