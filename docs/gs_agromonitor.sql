-- Procedure: inserir especie (cultura)
CREATE OR REPLACE PROCEDURE SP_INSERT_SPECIES(
    p_common_name     IN VARCHAR2,
    p_scientific_name IN VARCHAR2,
    p_min_humidity    IN NUMBER,
    p_max_humidity    IN NUMBER,
    p_frost_min_temp  IN NUMBER,
    p_watering_ml     IN NUMBER
) IS
    v_code VARCHAR2(20);
    v_msg  VARCHAR2(2000);
    v_user VARCHAR2(100) := USER;
BEGIN
    INSERT INTO TB_CAD_SPECIES
        (COMMON_NAME, SCIENTIFIC_NAME, MIN_HUMIDITY, MAX_HUMIDITY, FROST_MIN_TEMP, WATERING_ML)
    VALUES
        (p_common_name, p_scientific_name, p_min_humidity, p_max_humidity, p_frost_min_temp, p_watering_ml);
    COMMIT;
EXCEPTION
    WHEN DUP_VAL_ON_INDEX THEN
        v_code := SQLCODE;
        v_msg  := 'Cultura ja cadastrada: '||p_common_name;
        INSERT INTO TB_MON_ERROR_LOG (PROCEDURE_NAME,USER_NAME,ERROR_CODE,ERROR_MESSAGE)
        VALUES ('SP_INSERT_SPECIES',v_user,v_code,v_msg);
        COMMIT;
    WHEN VALUE_ERROR THEN
        v_code := SQLCODE;
        v_msg  := 'Dados invalidos para a cultura: '||p_common_name;
        INSERT INTO TB_MON_ERROR_LOG (PROCEDURE_NAME,USER_NAME,ERROR_CODE,ERROR_MESSAGE)
        VALUES ('SP_INSERT_SPECIES',v_user,v_code,v_msg);
        COMMIT;
    WHEN OTHERS THEN
        v_code := SQLCODE;
        v_msg  := SUBSTR(SQLERRM,1,2000);
        INSERT INTO TB_MON_ERROR_LOG (PROCEDURE_NAME,USER_NAME,ERROR_CODE,ERROR_MESSAGE)
        VALUES ('SP_INSERT_SPECIES',v_user,v_code,v_msg);
        COMMIT;
END;
