-- Cursor explicito 3: historico de alertas com quebra de grupo por severidade
DECLARE
    CURSOR c_alerts IS
        SELECT a.SEVERITY, a.ALERT_TYPE, a.MESSAGE, sl.POSITION, sp.COMMON_NAME,
               TO_CHAR(a.ALERT_TIME,'DD/MM/YYYY HH24:MI') AS when_txt
          FROM TB_MON_ALERT a
          JOIN TB_CAD_SLOT sl ON sl.ID = a.SLOT_ID
          JOIN TB_CAD_SPECIES sp ON sp.ID = sl.SPECIES_ID
         ORDER BY DECODE(a.SEVERITY,'CRITICAL',1,'MEDIUM',2,'LOW',3), a.ALERT_TIME;

    v_current_sev VARCHAR2(10) := NULL;
    v_group_count NUMBER := 0;
    v_grand_total NUMBER := 0;
BEGIN
    DBMS_OUTPUT.PUT_LINE('=====================================================');
    DBMS_OUTPUT.PUT_LINE('   CURSOR 3 - ALERTAS AGRUPADOS POR SEVERIDADE       ');
    DBMS_OUTPUT.PUT_LINE('=====================================================');

    FOR reg IN c_alerts LOOP
        -- Tomada de decisao: detectar mudanca de grupo (quebra)
        IF v_current_sev IS NULL OR reg.SEVERITY <> v_current_sev THEN
            IF v_current_sev IS NOT NULL THEN
                DBMS_OUTPUT.PUT_LINE('   Subtotal '||v_current_sev||': '||v_group_count);
                DBMS_OUTPUT.PUT_LINE('');
            END IF;
            v_current_sev := reg.SEVERITY;
            v_group_count := 0;
            DBMS_OUTPUT.PUT_LINE('--- Severidade: '||reg.SEVERITY||' ---');
        END IF;

        DBMS_OUTPUT.PUT_LINE('  ['||reg.when_txt||'] '||RPAD(reg.POSITION,5)||
            RPAD(reg.COMMON_NAME,12)||reg.ALERT_TYPE);
        v_group_count := v_group_count + 1;
        v_grand_total := v_grand_total + 1;
    END LOOP;

    -- Subtotal do ultimo grupo
    IF v_current_sev IS NOT NULL THEN
        DBMS_OUTPUT.PUT_LINE('   Subtotal '||v_current_sev||': '||v_group_count);
    END IF;
    DBMS_OUTPUT.PUT_LINE('');
    DBMS_OUTPUT.PUT_LINE('Total geral de alertas: '||v_grand_total);
END;
/

-- Cursor explicito 4: ranking de slots por leituras criticas (uso de WHILE e FETCH)
DECLARE
    CURSOR c_critical IS
        SELECT sl.POSITION, sp.COMMON_NAME, sp.MIN_HUMIDITY,
               COUNT(r.SLOT_ID) AS critical_count
          FROM TB_MON_READING r
          JOIN TB_CAD_SLOT sl ON sl.ID = r.SLOT_ID
          JOIN TB_CAD_SPECIES sp ON sp.ID = sl.SPECIES_ID
         WHERE r.HUMIDITY < sp.MIN_HUMIDITY
         GROUP BY sl.POSITION, sp.COMMON_NAME, sp.MIN_HUMIDITY
         ORDER BY critical_count DESC;

    v_pos      TB_CAD_SLOT.POSITION%TYPE;
    v_name     TB_CAD_SPECIES.COMMON_NAME%TYPE;
    v_min      TB_CAD_SPECIES.MIN_HUMIDITY%TYPE;
    v_count    NUMBER;
    v_rank     NUMBER := 0;
    v_priority VARCHAR2(15);
BEGIN
    DBMS_OUTPUT.PUT_LINE('=====================================================');
    DBMS_OUTPUT.PUT_LINE('   CURSOR 4 - RANKING DE SLOTS POR LEITURAS CRITICAS ');
    DBMS_OUTPUT.PUT_LINE('=====================================================');
    DBMS_OUTPUT.PUT_LINE(RPAD('Rank',6)||RPAD('Slot',8)||RPAD('Cultura',12)||
        RPAD('Criticas',10)||'Prioridade');
    DBMS_OUTPUT.PUT_LINE(RPAD('-',55,'-'));

    OPEN c_critical;
    -- Uso explicito de FETCH dentro de LOOP ... EXIT WHEN
    LOOP
        FETCH c_critical INTO v_pos, v_name, v_min, v_count;
        EXIT WHEN c_critical%NOTFOUND;

        v_rank := v_rank + 1;
        -- Tomada de decisao: prioridade de manutencao
        IF v_count >= 2 THEN
            v_priority := 'URGENTE';
        ELSIF v_count = 1 THEN
            v_priority := 'Atencao';
        ELSE
            v_priority := 'Normal';
        END IF;

        DBMS_OUTPUT.PUT_LINE(RPAD(v_rank,6)||RPAD(v_pos,8)||RPAD(v_name,12)||
            RPAD(v_count,10)||v_priority);
    END LOOP;
    CLOSE c_critical;

    IF v_rank = 0 THEN
        DBMS_OUTPUT.PUT_LINE('Nenhuma leitura critica registrada.');
    END IF;
END;
/

-- Bloco de relatorios gerenciais com JOIN (fecha os 5 relatorios exigidos)
DECLARE
    -- Variaveis para um WHILE LOOP de exemplo (faixas de umidade)
    v_band       NUMBER := 0;
    v_band_start NUMBER;
    v_band_end   NUMBER;
    v_qty        NUMBER;
BEGIN
    DBMS_OUTPUT.PUT_LINE('=====================================================');
    DBMS_OUTPUT.PUT_LINE('        RELATORIOS GERENCIAIS COM JOIN               ');
    DBMS_OUTPUT.PUT_LINE('=====================================================');

    -- Relatorio JOIN 1: leituras por cultura (media, minima e maxima)
    DBMS_OUTPUT.PUT_LINE('');
    DBMS_OUTPUT.PUT_LINE('--- Relatorio 1: estatisticas de umidade por cultura ---');
    DBMS_OUTPUT.PUT_LINE(RPAD('Cultura',12)||RPAD('Leituras',10)||
        RPAD('Media',8)||RPAD('Min',7)||'Max');
    DBMS_OUTPUT.PUT_LINE(RPAD('-',50,'-'));
    FOR r IN (
        SELECT sp.COMMON_NAME,
               COUNT(rd.SLOT_ID) AS qty,
               ROUND(AVG(rd.HUMIDITY),1) AS avg_h,
               MIN(rd.HUMIDITY) AS min_h,
               MAX(rd.HUMIDITY) AS max_h
          FROM TB_MON_READING rd
          JOIN TB_CAD_SLOT sl ON sl.ID = rd.SLOT_ID
          JOIN TB_CAD_SPECIES sp ON sp.ID = sl.SPECIES_ID
         GROUP BY sp.COMMON_NAME
         ORDER BY avg_h DESC
    ) LOOP
        DBMS_OUTPUT.PUT_LINE(RPAD(r.COMMON_NAME,12)||RPAD(r.qty,10)||
            RPAD(r.avg_h,8)||RPAD(r.min_h,7)||r.max_h);
    END LOOP;

    -- Relatorio JOIN 2: eventos de rega por origem
    DBMS_OUTPUT.PUT_LINE('');
    DBMS_OUTPUT.PUT_LINE('--- Relatorio 2: regas por origem (manual x automatica) ---');
    DBMS_OUTPUT.PUT_LINE(RPAD('Origem',14)||RPAD('Qtd',8)||'Volume total (ml)');
    DBMS_OUTPUT.PUT_LINE(RPAD('-',45,'-'));
    FOR r IN (
        SELECT we.ORIGIN,
               COUNT(we.ID) AS qty,
               SUM(we.VOLUME_ML) AS total_ml
          FROM TB_MON_WATERING_EVENT we
         GROUP BY we.ORIGIN
         ORDER BY qty DESC
    ) LOOP
        DBMS_OUTPUT.PUT_LINE(RPAD(r.ORIGIN,14)||RPAD(r.qty,8)||r.total_ml);
    END LOOP;

    -- Relatorio JOIN 3: regas automaticas com o usuario (LEFT JOIN, mostra NULL)
    DBMS_OUTPUT.PUT_LINE('');
    DBMS_OUTPUT.PUT_LINE('--- Relatorio 3: ultimas regas e responsavel ---');
    DBMS_OUTPUT.PUT_LINE(RPAD('Slot',8)||RPAD('Origem',12)||RPAD('Volume',9)||'Responsavel');
    DBMS_OUTPUT.PUT_LINE(RPAD('-',50,'-'));
    FOR r IN (
        SELECT sl.POSITION, we.ORIGIN, we.VOLUME_ML,
               NVL(u.NAME,'(sistema)') AS responsible
          FROM TB_MON_WATERING_EVENT we
          JOIN TB_CAD_SLOT sl ON sl.ID = we.SLOT_ID
          LEFT JOIN TB_CAD_USER u ON u.ID = we.USER_ID
         ORDER BY we.EVENT_TIME DESC
         FETCH FIRST 8 ROWS ONLY
    ) LOOP
        DBMS_OUTPUT.PUT_LINE(RPAD(r.POSITION,8)||RPAD(r.ORIGIN,12)||
            RPAD(r.VOLUME_ML,9)||r.responsible);
    END LOOP;

    -- Relatorio JOIN 4: previsoes com risco de geada e culturas afetadas
    DBMS_OUTPUT.PUT_LINE('');
    DBMS_OUTPUT.PUT_LINE('--- Relatorio 4: datas de risco de geada ---');
    DBMS_OUTPUT.PUT_LINE(RPAD('Data',12)||RPAD('Min.Temp',10)||RPAD('Prob.Geada',12)||'Culturas em risco');
    DBMS_OUTPUT.PUT_LINE(RPAD('-',60,'-'));
    FOR r IN (
        SELECT TO_CHAR(cf.FORECAST_DATE,'DD/MM/YYYY') AS dt,
               cf.MIN_TEMP, cf.FROST_PROB,
               (SELECT COUNT(*) FROM TB_CAD_SLOT sl2
                  JOIN TB_CAD_SPECIES sp2 ON sp2.ID = sl2.SPECIES_ID
                 WHERE sl2.STATUS = 'ACTIVE'
                   AND sp2.FROST_MIN_TEMP >= cf.MIN_TEMP) AS at_risk
          FROM TB_MON_CLIMATE_FORECAST cf
         WHERE cf.FROST_PROB >= 50
         ORDER BY cf.FORECAST_DATE
    ) LOOP
        DBMS_OUTPUT.PUT_LINE(RPAD(r.dt,12)||RPAD(r.MIN_TEMP,10)||
            RPAD(r.FROST_PROB||'%',12)||r.at_risk);
    END LOOP;

    -- Relatorio JOIN 5: alertas por cultura e tipo
    DBMS_OUTPUT.PUT_LINE('');
    DBMS_OUTPUT.PUT_LINE('--- Relatorio 5: alertas por cultura e tipo ---');
    DBMS_OUTPUT.PUT_LINE(RPAD('Cultura',12)||RPAD('Tipo',16)||'Qtd');
    DBMS_OUTPUT.PUT_LINE(RPAD('-',40,'-'));
    FOR r IN (
        SELECT sp.COMMON_NAME, a.ALERT_TYPE, COUNT(a.ID) AS qty
          FROM TB_MON_ALERT a
          JOIN TB_CAD_SLOT sl ON sl.ID = a.SLOT_ID
          JOIN TB_CAD_SPECIES sp ON sp.ID = sl.SPECIES_ID
         GROUP BY sp.COMMON_NAME, a.ALERT_TYPE
         ORDER BY sp.COMMON_NAME, qty DESC
    ) LOOP
        DBMS_OUTPUT.PUT_LINE(RPAD(r.COMMON_NAME,12)||RPAD(r.ALERT_TYPE,16)||r.qty);
    END LOOP;

    -- Distribuicao de leituras por faixa de umidade (uso de WHILE LOOP)
    DBMS_OUTPUT.PUT_LINE('');
    DBMS_OUTPUT.PUT_LINE('--- Relatorio extra: distribuicao por faixa de umidade ---');
    DBMS_OUTPUT.PUT_LINE(RPAD('Faixa',14)||'Leituras');
    DBMS_OUTPUT.PUT_LINE(RPAD('-',28,'-'));
    WHILE v_band < 100 LOOP
        v_band_start := v_band;
        v_band_end   := v_band + 20;
        SELECT COUNT(*) INTO v_qty
          FROM TB_MON_READING
         WHERE HUMIDITY >= v_band_start AND HUMIDITY < v_band_end;
        DBMS_OUTPUT.PUT_LINE(RPAD(v_band_start||'-'||v_band_end||'%',14)||v_qty);
        v_band := v_band + 20;
    END LOOP;
END;
