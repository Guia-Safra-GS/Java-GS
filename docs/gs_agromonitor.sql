-- #####################################################################
-- # 4) AUTOMACAO: FUNCTION + PACKAGE + TRIGGER
-- #   O coracao da solucao. A cada leitura inserida, o banco decide
-- #   sozinho se precisa regar e/ou alertar, cruzando o valor lido com
-- #   a faixa ideal da cultura daquele slot.
-- #####################################################################

-- Function de apoio: classifica a severidade de uma leitura de umidade
-- comparando o valor lido com o minimo tolerado pela cultura.
-- Retorna: 'OK', 'LOW' ou 'CRITICAL'.
CREATE OR REPLACE FUNCTION FN_HUMIDITY_SEVERITY(
    p_humidity IN NUMBER,
    p_min      IN NUMBER
) RETURN VARCHAR2 IS
    v_severity VARCHAR2(10);
    v_gap      NUMBER;
BEGIN
    v_gap := p_min - p_humidity;
    -- Tomada de decisao por faixa de deficit de umidade
    IF v_gap <= 0 THEN
        v_severity := 'OK';            -- dentro ou acima do minimo
    ELSIF v_gap <= 10 THEN
        v_severity := 'LOW';           -- pouco abaixo do minimo
    ELSE
        v_severity := 'CRITICAL';      -- muito abaixo do minimo
    END IF;
    RETURN v_severity;
END;
/

-- Package de automacao agronomica: especificacao (interface publica)
CREATE OR REPLACE PACKAGE PKG_AGRO_AUTOMATION AS
    -- Avalia uma leitura recem-inserida e dispara rega/alerta se necessario.
    -- Chamada pela trigger TRG_READING_AUTOMATION.
    PROCEDURE evaluate_reading(
        p_slot_id   IN NUMBER,
        p_humidity  IN NUMBER
    );

    -- Varre as previsoes de uma data e gera alertas de geada para as
    -- culturas sensiveis (cuja FROST_MIN_TEMP esteja ameacada).
    PROCEDURE check_frost_risk(
        p_forecast_date IN DATE
    );
END PKG_AGRO_AUTOMATION;
/

-- Package de automacao agronomica: corpo (implementacao)
CREATE OR REPLACE PACKAGE BODY PKG_AGRO_AUTOMATION AS

    PROCEDURE evaluate_reading(
        p_slot_id  IN NUMBER,
        p_humidity IN NUMBER
    ) IS
        v_min_humidity TB_CAD_SPECIES.MIN_HUMIDITY%TYPE;
        v_watering_ml  TB_CAD_SPECIES.WATERING_ML%TYPE;
        v_common_name  TB_CAD_SPECIES.COMMON_NAME%TYPE;
        v_severity     VARCHAR2(10);
        v_code         VARCHAR2(20);
        v_user         VARCHAR2(100) := USER;
        v_msg          VARCHAR2(2000);
    BEGIN
        -- Busca a regra da cultura plantada neste slot (tabela -> variaveis)
        SELECT sp.MIN_HUMIDITY, sp.WATERING_ML, sp.COMMON_NAME
          INTO v_min_humidity, v_watering_ml, v_common_name
          FROM TB_CAD_SLOT sl
          JOIN TB_CAD_SPECIES sp ON sp.ID = sl.SPECIES_ID
         WHERE sl.ID = p_slot_id;

        -- Classifica a leitura usando a function de apoio
        v_severity := FN_HUMIDITY_SEVERITY(p_humidity, v_min_humidity);

        -- Decisao de negocio conforme a severidade
        IF v_severity = 'CRITICAL' THEN
            -- Rega automatica de emergencia (USER_ID nulo = acionada pelo sistema)
            INSERT INTO TB_MON_WATERING_EVENT (SLOT_ID, USER_ID, ORIGIN, VOLUME_ML)
            VALUES (p_slot_id, NULL, 'AUTOMATIC', v_watering_ml);

            INSERT INTO TB_MON_ALERT (SLOT_ID, ALERT_TYPE, SEVERITY, MESSAGE)
            VALUES (p_slot_id, 'LOW_HUMIDITY', 'CRITICAL',
                    'Umidade critica em '||v_common_name||' ('||p_humidity
                    ||'%). Rega automatica de '||v_watering_ml||'ml acionada.');
        ELSIF v_severity = 'LOW' THEN
            -- Apenas alerta, sem rega automatica
            INSERT INTO TB_MON_ALERT (SLOT_ID, ALERT_TYPE, SEVERITY, MESSAGE)
            VALUES (p_slot_id, 'LOW_HUMIDITY', 'MEDIUM',
                    'Umidade baixa em '||v_common_name||' ('||p_humidity
                    ||'%). Monitorar de perto.');
        END IF;
        -- Severidade 'OK' nao gera nenhuma acao.
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            -- Slot sem cultura associada: registra no log e nao interrompe a carga
            v_code := SQLCODE;
            INSERT INTO TB_MON_ERROR_LOG (PROCEDURE_NAME,USER_NAME,ERROR_CODE,ERROR_MESSAGE)
            VALUES ('PKG_AGRO_AUTOMATION.evaluate_reading',v_user,v_code,
                    'Slot '||p_slot_id||' sem cultura associada na avaliacao da leitura.');
        WHEN OTHERS THEN
            v_code := SQLCODE;
            v_msg  := SUBSTR(SQLERRM,1,2000);
            INSERT INTO TB_MON_ERROR_LOG (PROCEDURE_NAME,USER_NAME,ERROR_CODE,ERROR_MESSAGE)
            VALUES ('PKG_AGRO_AUTOMATION.evaluate_reading',v_user,v_code,v_msg);
    END evaluate_reading;

    PROCEDURE check_frost_risk(
        p_forecast_date IN DATE
    ) IS
        v_min_temp   TB_MON_CLIMATE_FORECAST.MIN_TEMP%TYPE;
        v_frost_prob TB_MON_CLIMATE_FORECAST.FROST_PROB%TYPE;
        v_count      NUMBER := 0;
        v_code       VARCHAR2(20);
        v_user       VARCHAR2(100) := USER;
        v_msg        VARCHAR2(2000);

        -- Cursor explicito: culturas ativas sensiveis a geada
        CURSOR c_sensitive_slots IS
            SELECT sl.ID AS slot_id, sp.COMMON_NAME, sp.FROST_MIN_TEMP
              FROM TB_CAD_SLOT sl
              JOIN TB_CAD_SPECIES sp ON sp.ID = sl.SPECIES_ID
             WHERE sl.STATUS = 'ACTIVE'
               AND sp.FROST_MIN_TEMP IS NOT NULL;
    BEGIN
        -- Busca a previsao da data informada (tabela -> variaveis)
        SELECT MIN_TEMP, FROST_PROB
          INTO v_min_temp, v_frost_prob
          FROM TB_MON_CLIMATE_FORECAST
         WHERE FORECAST_DATE = p_forecast_date;

        -- Se nao ha risco relevante de geada, encerra sem alertas
        IF v_frost_prob < 50 THEN
            DBMS_OUTPUT.PUT_LINE('Sem risco relevante de geada em '
                ||TO_CHAR(p_forecast_date,'DD/MM/YYYY')
                ||' (probabilidade '||v_frost_prob||'%).');
            RETURN;
        END IF;

        -- Para cada cultura sensivel, verifica se a temperatura ameaca
        FOR reg IN c_sensitive_slots LOOP
            IF v_min_temp <= reg.FROST_MIN_TEMP THEN
                INSERT INTO TB_MON_ALERT (SLOT_ID, ALERT_TYPE, SEVERITY, MESSAGE)
                VALUES (reg.slot_id, 'FROST_RISK', 'CRITICAL',
                        'Risco de geada para '||reg.COMMON_NAME||' em '
                        ||TO_CHAR(p_forecast_date,'DD/MM/YYYY')||'. Minima prevista '
                        ||v_min_temp||'C (limite '||reg.FROST_MIN_TEMP||'C).');
                v_count := v_count + 1;
            END IF;
        END LOOP;

        COMMIT;
        DBMS_OUTPUT.PUT_LINE('Verificacao de geada em '
            ||TO_CHAR(p_forecast_date,'DD/MM/YYYY')||': '
            ||v_count||' alerta(s) gerado(s).');
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            DBMS_OUTPUT.PUT_LINE('Nao ha previsao cadastrada para '
                ||TO_CHAR(p_forecast_date,'DD/MM/YYYY')||'.');
        WHEN OTHERS THEN
            v_code := SQLCODE;
            v_msg  := SUBSTR(SQLERRM,1,2000);
            INSERT INTO TB_MON_ERROR_LOG (PROCEDURE_NAME,USER_NAME,ERROR_CODE,ERROR_MESSAGE)
            VALUES ('PKG_AGRO_AUTOMATION.check_frost_risk',v_user,v_code,v_msg);
    END check_frost_risk;

END PKG_AGRO_AUTOMATION;
/

-- Trigger: a cada nova leitura inserida, aciona a avaliacao automatica.
-- AFTER INSERT FOR EACH ROW: escreve apenas em WATERING_EVENT e ALERT
-- (tabelas distintas de READING), evitando o erro de mutating table.
CREATE OR REPLACE TRIGGER TRG_READING_AUTOMATION
AFTER INSERT ON TB_MON_READING
FOR EACH ROW
BEGIN
    PKG_AGRO_AUTOMATION.evaluate_reading(:NEW.SLOT_ID, :NEW.HUMIDITY);
END;
/

